#!/usr/bin/env bash
# Regenerates repo-map.md: every source file, its size, and its exports.
# Run from anywhere: bash .claude/skills/lean/scripts/map.sh
set -euo pipefail
root="$(git -C "$(dirname "$0")" rev-parse --show-toplevel)"
out="$root/.claude/skills/lean/repo-map.md"
cd "$root"
{
  echo "# Repo map (generated by scripts/map.sh at $(git rev-parse --short HEAD))"
  echo
  echo "Format: \`path (lines): exports\`. Regenerate when files are added, removed or renamed."
  echo
  git ls-files 'app/*' 'lib/*' 'components/*' | grep -E '\.(ts|tsx|css)$' | while read -r f; do
    ex=$(grep -hoE '^export (default )?(async )?(function|const|type|interface|class|enum) [A-Za-z0-9_]+' "$f" \
         | awk '{print $NF}' | paste -sd' ' - || true)
    echo "- \`$f\` ($(wc -l <"$f")): ${ex:-—}"
  done
} >"$out"
echo "wrote $out"
